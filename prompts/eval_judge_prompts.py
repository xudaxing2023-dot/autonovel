# ============================================================================
# Full Novel 评估 Prompt (章节摘要拼接 + 补充维度)
# ============================================================================

def build_full_novel_eval_prompt(
    manuscript_text: str = "",
    outline_text: str = "",
    voice_text: str = "",
) -> str:
    """构建全文评估 prompt。

    对齐原版 FULL_NOVEL_PROMPT (evaluate.py line 560-650)，
    关键改进：
    — 使用每章首尾各 500 字的摘要拼接代替全文截断 25000 字
    — 补充 4 个维度：world_consistency / voice_consistency /
      weakest_chapter / top_suggestion
    """

    # —— 章节摘要拼接 ——
    # 尝试从 CHAPTERS_DIR 读取各章节，每章取首尾各 500 字
    chapter_summaries = ""
    chapter_count = 0

    try:
        ch_files = sorted(CHAPTERS_DIR.glob("ch_*.md"))
        if ch_files:
            for f in ch_files:
                text = f.read_text(encoding="utf-8")
                head = text[:500]
                tail = text[-500:] if len(text) > 1000 else ""
                ch_name = f.stem.replace("ch_", "")
                chapter_summaries += (
                    f"\n### 第 {ch_name} 章 开头\n{head}\n"
                )
                if tail:
                    chapter_summaries += (
                        f"\n### 第 {ch_name} 章 结尾\n{tail}\n"
                    )
                chapter_summaries += "\n---\n"
                chapter_count += 1
    except Exception:
        # 回退：使用传入的 manuscript_text 截断
        chapter_summaries = manuscript_text[:25000] if manuscript_text else ""
        chapter_count = 0

    # 如果章节摘要为空但 manuscript_text 有内容，回退到截断模式
    if not chapter_summaries and manuscript_text:
        chapter_summaries = manuscript_text[:25000]

    outline_section = ""
    if outline_text:
        outline_section = f"""
【大纲参考】
{outline_text[:3000]}
"""

    voice_section = ""
    if voice_text:
        voice_section = f"""
【文风定义】
{voice_text[:2000]}
"""

    return f"""请对以下长篇小说的完整文本进行全局评审打分。

{SCORING_CALIBRATION}
{MANDATORY_GAP_FIX}

【小说章节摘要（共{chapter_count}章，每章首尾各 500 字）】
{chapter_summaries if chapter_summaries else "（无章节数据）"}

{outline_section}
{voice_section}

【评分维度——6 个全局维度，每维 1-10 分】

━━━ STRUCTURE（结构——权重 25%）━━━

1. arc_coherence (弧线连贯性):
   主角的成长/变化轨迹是否贯穿全书？是否有明显的转折点？
   各幕之间的过渡是否有因果逻辑（而非仅按时间顺序排列）？
   副线是否与主线有意义的交叉（而非平行运行永不相交）？
   评分: ___/10  |  最大弱点: ___  |  改进方案: ___

2. payoff_satisfaction (回报满足度):
   早期种植的伏笔是否在后期收获？收获时是否有情感冲击力？
   高潮章节是否兑现了前文的承诺？
   "大反转"是否在重读时有迹可循（而非凭空出现）？
   是否有未解决的重要线索（遗忘的伏笔）？
   评分: ___/10  |  最大弱点: ___  |  改进方案: ___

━━━ CONSISTENCY（一致性——权重 25%）━━━

3. world_consistency (世界观一致性):
   世界观核心规则（无论力量体系、社会制度或时代背景）是否从头到尾保持一致？
   是否有世界观上的"便利性例外"（因情节需要而临时修改规则）？
   地理/时间线/社会结构是否有前后矛盾？
   评分: ___/10  |  最大弱点: ___  |  改进方案: ___

4. voice_consistency (文风一致性):
   全书文风是否统一？是否有章节风格突变（像换了作者）？
   叙事距离和视角规则是否一致？
   对话风格在各章之间是否保持角色辨识度？
   评分: ___/10  |  最大弱点: ___  |  改进方案: ___

━━━ READER EXPERIENCE（读者体验——权重 25%）━━━

5. momentum (动力):
   是否存在"读者可能放下书"的章节（节奏骤降/信息倾泻/无张力场景）？
   各章结尾是否都有翻页动力？
   全书中间部分（第 2 幕）是否有"第二幕低谷"问题？
   评分: ___/10  |  最大弱点: ___  |  改进方案: ___

6. emotional_range (情感广度):
   小说是否提供了充分的情绪变化（而非单一色调）？
   是否有真正的低点让高潮有意义？
   幽默/温情/紧张/悲伤等是否有合理的分布？
   评分: ___/10  |  最大弱点: ___  |  改进方案: ___

━━━ 额外输出 ━━━

7. weakest_chapter (最弱章节):
   指出全书中最需要修订的一章及其原因。引用具体位置。

8. top_suggestion (最有杠杆效应的建议):
   一条建议——如果只改一件事，改什么能最大程度提升全书质量？
   必须具体、可操作。

9. overall_score (综合评分): ___/10
   (structure 25% + consistency 25% + reader_experience 25%
    + 25% 基于你对全书品质的整体判断)

{FINAL_CHECK}

请用中文输出。每个维度都包括：评分、最大弱点（引用具体章节/位置）、具体改进方案。"""