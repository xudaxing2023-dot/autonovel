"""
prompts/world_prompts.py — 世界观构建 Prompt (通用中文)

原 autonovel 的 gen_world.py 硬编码了「Tonal Law / Cantamura / Cass」。
重构为参数化通用中文版本：从 {story_summary} 提取世界观元素。
"""

from core.config import config


def build_world_prompt(seed_text: str, voice_part2: str = "", craft_text: str = "") -> str:
    """构建世界观生成 prompt。"""

    cfg = config
    cfg.load()

    story = seed_text or cfg.story_summary
    total_ch = cfg.total_chapters if cfg.loaded else 24

    return f"""请为这部长篇小说构建一个完整的世界观设定文档（WORLD.MD）。
这份文档是小说世界的权威参考——作者应能仅凭此文档解决所有世界观相关问题。

【故事梗概】
{story}

【小说总章节数】{total_ch} 章

{('【文风身份】' + voice_part2) if voice_part2 else ''}

【叙事技艺参考（遵循以下原则）】
{'（来自 CRAFT.md）' + craft_text if craft_text else '— 核心规则/特殊体系需要有明确的规则、代价和限制\n— 代价/限制的叙事比重应 ≥ 能力本身\n— 追溯核心设定对社会、经济、法律、宗教的连锁影响\n— 历史必须制造【当前矛盾】，而非单纯的背景板\n— 地理必须具体、有感官特征（气味、声音、温度、质感）\n— 冰山原则：暗示的比陈述的多\n— 互联性：牵一发而动全身'}

【文档结构 — 请按以下章节组织内容】

## 一、宇宙观与历史
列出重大事件时间线。聚焦于制造【当前矛盾】的事件。
包括创世神话（若有）、关键转折点、与主线剧情直接相关的近期事件。

## 二、核心规则/特殊体系（根据题材调整）
### 2.1 硬规则
具体、可验证的规则。谁可以使用？怎样使用？什么情况下失效？
明确标注【代价】和【限制】。

### 2.2 特殊设定
如果主角有独特能力/天赋/金手指/特殊资源，描述它的运作方式、独特代价、内在逻辑。

### 2.3 社会影响
该体系如何影响：政治治理、商业贸易、教育体系、阶级结构、
犯罪行为、家庭生活、童年与成长、衰老与死亡？

## 三、地理
主角活动区域的地貌、城市布局、关键地点。
至少描述 2-3 个不同区域，每个区域有独特的感官特征。
（如果题材是都市/校园/职场等，则描述关键场景和空间布局）

## 四、势力与政治
谁掌权？谁想掌权？谁被碾压？
至少 3-4 个势力/群体，利益相互冲突。

## 五、生态/科技/自然世界
这个世界的自然环境或科技水平有什么独特之处？

## 六、文化细节
风俗、禁忌、节日、饮食、服饰、成长仪式——
让日常生活感觉【具体】而非泛泛而谈的概念。

## 七、内部一致性规则
作者不可违反的硬约束。这个世界的「物理定律」。

【重要指引】
1. 要【具体】。不要泛写「城市分几个区」，而是命名它们、描述感官特征。
2. 每条规则旁边都要标注【代价】或【限制】。
3. 每个章节至少留 2-3 条未解释的事实，暗示更深层的体系（冰山深度）。
4. 事实要【互联】：核心规则应塑造政治，地理应塑造文化，历史应解释当前冲突。
5. 用简洁、直接的汉语写作。避免 AI 套话（如「宛如一幅画卷」「如同一首交响乐」等）。
6. 世界应让人感觉是「被居住过的」，而非「被设计出来的」。
   思考：早饭是什么味道？小孩玩什么？老人抱怨什么？

写出完整的世界观设定文档。"""


