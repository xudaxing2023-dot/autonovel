"""
prompts/review_prompts.py — 深度审阅 Prompt (通用中文)

原版 review.py 使用 Opus 进行深度审阅。
中文版替代——全手稿提交给裁判模型，产出结构化审阅报告。
"""


def build_review_prompt(manuscript_text: str, outline_text: str = "") -> str:
    """构建深度审阅 prompt。"""

    # 限制手稿长度，避免超出 context window
    truncated = manuscript_text[:30000] if len(manuscript_text) > 30000 else manuscript_text

    return f"""请你以专业文学审稿人的身份，对以下长篇小说进行深度审阅。

{('【大纲对照】' + outline_text[:5000]) if outline_text else ''}

【手稿内容（可能截断，请基于可见部分评审）】
{truncated}

【请按以下维度进行结构化评审】

## 一、整体评价（★ 评分，1-5★）
— 总体印象
— 这部小说最大的优点
— 这部小说最需要改进的地方

## 二、结构诊断
— 三幕/四幕结构是否清晰？
— 节奏曲线是否合理？（有无疲软中间/节奏崩塌/高潮提前）
— 伏笔回收是否完成？（有无悬而未决的线索）
— 角色弧是否完成？（主角是否发生了真正的变化？）

## 三、章节级问题（逐章标注）
对每一章，标注：
— 评分（1-10）
— 主要问题分类: MAJOR / MINOR / QUALIFIED（合格）
— 问题描述（具体，可操作）

## 四、模式级诊断
— 反复出现的 AI 写作痕迹类型
— 常见节奏问题类型
— 常见的「展示后解释」模式
— 其他系统性问题

## 五、优先级建议
— 哪些问题必须立即修复（会显著影响阅读体验）？
— 哪些问题可以接受（在可接受范围内）？

请用中文写作。审阅要具体、可操作、不留情面但建设性。"""


